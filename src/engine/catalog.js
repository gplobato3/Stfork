function deepFreeze(o) {
    if (o && typeof o === 'object' && !Object.isFrozen(o)) {
        Object.freeze(o);
        for (const v of Object.values(o)) deepFreeze(v);
    }
    return o;
}

/** Frozen catalog, stable order (category, then authoring order). */
export const CATALOG = deepFreeze(RAW_CATALOG.map((d) => ({ requires: {}, onFailure: [], keywords: [], ...d })));

const BY_ID = new Map(CATALOG.map((d) => [d.id, d]));

/** @returns {?import('../contract/events.js').ActionDef} */
export function getActionDef(id) {
    return BY_ID.get(id) || null;
}

