/**
 * @file src/engine/catalog.js
 * The action catalog (DESIGN §3.3). Pure data: every ActionDef uses SELF / TARGET
 * placeholders in its effects; the engine resolves them at execution time.
 *
 * Engine extensions to the ActionDef / Requirement contract (ignored by other modules):
 *   - `acceptance`: 'trade' | 'energy' | 'alliance' | 'defense' | 'ceasefire' | 'peace'.
 *     Diplomatic proposals succeed by AI acceptance (relation, personality, power) instead
 *     of a ChanceSpec. When an AI proposes to the PLAYER, an engine GameEvent is queued.
 *   - `special`: name of a scripted hook in actions.js (e.g. 'demobilize', 'nuclear_strike').
 *   - Requirement keys `noPactWithTarget` (pact type; 'nonAggression' = post-war truce), `strongerThanTarget`, `targetAtWar`,
 *     `mobilized`, `notMobilized`, `notCeasefireWithTarget`.
 */

